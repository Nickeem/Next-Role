"""Artifact storage behind a small protocol, with a local-directory implementation.

Keys are generated by the server (``<bundle_id>/<artifact_id>.<ext>``) and never taken from
user input; they are still validated so a bad key cannot escape the root. Writes are atomic:
a temporary file is written and fsynced, then renamed into place.
"""

import hashlib
import os
import re
import tempfile
import time
from datetime import timedelta
from pathlib import Path
from typing import Protocol

# <bundle id>/<artifact id>-<attempt>.<ext>
_KEY = re.compile(r"^[0-9a-f-]{36}/[0-9a-f-]{36}-\d{1,3}\.(pdf|docx)$")


class ArtifactStore(Protocol):
    def put(self, key: str, data: bytes) -> str:
        """Store ``data`` under ``key`` and return its SHA-256 (hex)."""
        ...

    def get(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None: ...

    def keys(self) -> list[str]: ...

    def age(self, key: str) -> timedelta:
        """How long ago the file was written."""
        ...


class StorageError(Exception):
    """The file is missing, unreadable, or does not match its recorded hash."""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


class LocalArtifactStore:
    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        if not _KEY.fullmatch(key):
            raise StorageError("invalid storage key")
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):  # pragma: no cover - the pattern prevents it
            raise StorageError("invalid storage key")
        return path

    def put(self, key: str, data: bytes) -> str:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o750)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            Path(tmp).chmod(0o640)
            Path(tmp).replace(path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise
        # Make the rename itself durable before a database row can point at the file.
        directory = os.open(path.parent, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
        return sha256(data)

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except OSError as exc:
            raise StorageError(type(exc).__name__) from exc

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def age(self, key: str) -> timedelta:
        try:
            written = self._path(key).stat().st_mtime
        except OSError as exc:
            raise StorageError(type(exc).__name__) from exc
        return timedelta(seconds=max(0.0, time.time() - written))

    def keys(self) -> list[str]:
        if not self.root.is_dir():
            return []
        return sorted(
            str(p.relative_to(self.root))
            for p in self.root.glob("*/*")
            if p.is_file() and _KEY.fullmatch(str(p.relative_to(self.root)))
        )


def read_verified(store: ArtifactStore, key: str, expected_sha256: str) -> bytes:
    """Read a file and check it still matches the hash recorded when it was rendered."""
    data = store.get(key)
    if sha256(data) != expected_sha256:
        raise StorageError("artifact does not match its recorded hash")
    return data
